#!/usr/bin/env python3
"""Pack fixed-cell body renders and export shared pose contracts for Godot."""
import hashlib
import importlib.util
import json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'Art/Meshy/animation_v2'
spec=importlib.util.spec_from_file_location('previous_packer',ROOT/'tools/pack_prerendered.py')
old=importlib.util.module_from_spec(spec);spec.loader.exec_module(old)
CELLS={'baldwin':(128,128,32,96),'custodio':(128,96,64,72),'custodio_sellado':(128,96,64,72),'acolito':(96,96,48,72),'abad':(256,160,128,96)}


# Keep literal GDScript data importable in exported builds, including every pose.
def write_data(name,data):
    p=ROOT/'Scripts/Presentation'/f'{name}.gd';p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text('extends RefCounted\n\n# Generated by tools/pack_animation_v2.py; body and equipment share these poses.\nconst DATA = '+json.dumps(data,indent=2)+'\n')


# Downsample once, retaining the frame and hand anchor rather than cropping each pose.
def pack():
    palette,_=old.material_palette();manifest=[];player={};enemies={};previews=[]
    for actor,(w,h,rx,ry) in CELLS.items():
        clips=json.loads((ART/f'{actor}_poses.json').read_text());frames=[];ranges={};poses=[];start=0
        for clip,info in clips.items():
            clipframes=[]
            for i in range(info['count']):
                p=ART/'frames'/actor/clip/f'{i:03d}.png'
                with Image.open(p) as image:
                    if image.mode!='RGBA' or image.size!=(w*4,h*4):raise ValueError(f'Invalid frame {p}')
                    frame=old.finish_frame(image,(w,h),palette,110)
                box=frame.getbbox()
                if not box or box[0]==0 or box[1]==0 or box[2]==w:raise ValueError(f'Clipped body {actor}/{clip}/{i}: {box}')
                clipframes.append(frame)
            ranges[clip]={'start':start,'count':info['count'],'fps':info['fps'],'loop':info['loop']}
            start+=info['count'];poses.extend(info['poses']);frames.extend(clipframes)
            previews.append((actor,clip,clipframes,info['poses']))
            if actor=='baldwin':
                target=ROOT/'Sprites/Characters/Baldwin'/f'{clip}.png'
                save_sheet(target,clipframes,w,h,manifest)
                player[clip]=info
        if actor!='baldwin':
            target=ROOT/'Sprites'/('Bosses/abad.png' if actor=='abad' else f'Enemies/{actor}.png')
            save_sheet(target,frames,w,h,manifest,columns=8 if actor=='abad' else None)
            enemies[actor]={'cell':[w,h],'root':[rx,ry],'clips':ranges,'poses':poses}
            if actor=='abad':enemies[actor].update({'columns':8,'rows':11})
    write_data('BaldwinPoseData',player);write_data('EnemyPoseData',enemies)
    (ART/'pack_manifest.json').write_text(json.dumps({'sheets':manifest,'frames':sum(v['frames'] for v in manifest),'source_scale':4},indent=2)+'\n')
    preview(previews)
    print(f'Packed {len(manifest)} body sheets / {sum(v["frames"] for v in manifest)} frames')


# Store the exact installed texture digest for verification before publishing.
def save_sheet(path,frames,w,h,manifest,columns=None):
    path.parent.mkdir(parents=True,exist_ok=True);columns=columns or len(frames);rows=(len(frames)+columns-1)//columns;sheet=Image.new('RGBA',(w*columns,h*rows))
    for i,frame in enumerate(frames):sheet.paste(frame,((i%columns)*w,(i//columns)*h))
    sheet.save(path)
    manifest.append({'file':str(path.relative_to(ROOT)),'cell':[w,h],'frames':len(frames),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})


# Create looping motion previews from actual body frames, without synthesizing in-betweens.
def preview(items):
    out=ROOT/'docs/animation_v2';out.mkdir(parents=True,exist_ok=True)
    chosen=[row for row in items if row[0]=='baldwin' and row[1] in ('Idle','Walk','Dash','AttackSwordActive','AttackMaceActive')]
    for actor,clip,frames,poses in chosen:
        sequence=[]
        for frame in frames:
            bg=Image.new('RGB',(384,384),'#151924');large=frame.resize((384,384),Image.Resampling.NEAREST);bg.paste(large,(0,0),large);sequence.append(bg)
        sequence[0].save(out/f'body_{clip}.gif',save_all=True,append_images=sequence[1:],duration=90 if clip in ('Idle','Walk') else 45,loop=0,disposal=2)
    rows=[]
    for actor,clip,frames,_ in items:
        indexes=sorted(set([0,len(frames)//2,len(frames)-1]))
        rows.append((f'{actor} / {clip}',[frames[i].resize((frames[i].width*2,frames[i].height*2),Image.Resampling.NEAREST) for i in indexes]))
    old.gallery(rows,ART/'gallery.png')


if __name__=='__main__':pack()
